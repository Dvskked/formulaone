export const getCircuit = (id) => CIRCUITS.find((c) => c.id === id) || CIRCUITS[0];

/** Ordered calendar for a given season year (round order is fixed). */
export function buildCalendar(year) {
  return CIRCUITS.map((c, i) => ({
    round: i + 1,
    year,
    circuitId: c.id,
    name: `${c.short} Grand Prix`,
    fullName: c.name,
    country: c.country,
    flag: c.flag,
    laps: c.laps,
  }));
}

